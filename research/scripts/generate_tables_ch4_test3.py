# TABLE T3-B: Computational Functionalism Indicators (tab:t3_cf_indicators)
# ══════════════════════════════════════════════════════════════════════════

def make_t3_cf_indicators():
    detailed_path = RESULTS / "detailed_results.csv"
    stats_path = RESULTS / "summary_statistics.json"
    if not detailed_path.exists():
        print("  ERROR: detailed_results.csv not found for t3_cf_indicators")
        return

    detailed_df = pd.read_csv(detailed_path)
    if detailed_df.empty:
        print("  ERROR: detailed_results.csv is empty for t3_cf_indicators")
        return

    stats = {}
    if stats_path.exists():
        stats = json.loads(stats_path.read_text())

    cf_mask = detailed_df["is_cf"].astype(bool)
    cf_conf = pd.to_numeric(detailed_df.get("cf_confidence", 0), errors="coerce").fillna(0.0)
    trace_mask = detailed_df.get("is_traceable", False)
    trace_mask = pd.Series(trace_mask).astype(bool)
    hybrid_mask = detailed_df.get("is_hybrid", False)
    hybrid_mask = pd.Series(hybrid_mask).astype(bool)

    n_total = len(detailed_df)
    n_cf = int(cf_mask.sum())
    n_non_cf = int((~cf_mask).sum())
    cf_rate = (n_cf / n_total) if n_total else 0.0
    non_cf_rate = (n_non_cf / n_total) if n_total else 0.0

    cf_hi = int((cf_conf >= 0.5).sum())
    cf_lo = int(((cf_conf > 0.0) & (cf_conf < 0.5)).sum())
    cf_hi_rate = (cf_hi / n_total) if n_total else 0.0
    cf_lo_rate = (cf_lo / n_total) if n_total else 0.0

    cf_trace_rate = float(trace_mask[cf_mask].mean()) if n_cf else 0.0
    cf_hybrid_rate = float(hybrid_mask[cf_mask].mean()) if n_cf else 0.0

    cf_indicators = [
        ("Computational functionalist flag", "Rows with is\\_cf = True (strict binary CF assignment)", cf_rate * 100.0),
        ("Non-CF assignment", "Rows with is\\_cf = False", non_cf_rate * 100.0),
        ("High CF confidence", "Rows with cf\\_confidence $\\geq 0.5$", cf_hi_rate * 100.0),
        ("Low non-zero CF confidence", "Rows with $0 < \\mathrm{cf\\_confidence} < 0.5$", cf_lo_rate * 100.0),
        ("Traceable among CF rows", "Rows with is\\_traceable = True within is\\_cf subset", cf_trace_rate * 100.0),
        ("Hybrid among CF rows", "Rows with is\\_hybrid = True within is\\_cf subset", cf_hybrid_rate * 100.0),
    ]

    body_rows = []
    for indicator, description, rate in cf_indicators:
        body_rows.append(
            f"        {indicator} & {description} & {rate:.2f} \\\\"
        )

    body = "\n".join(body_rows)
    table_body = textwrap.dedent(f"""\
        \\toprule
        \\textbf{{Indicator}} & \\textbf{{Operational Definition}} & \\textbf{{Detection Rate (\\%)}} \\\\
        \\midrule
{body}
        \\bottomrule""")

    tex = HEADER + "\n" + style_table_block(
        caption=(
            f"Test 3 computational functionalism indicators derived from canonical results "
            f"($N={n_total}$). Mean CF confidence score across all theories: "
            f"{stats.get('mean_cf_confidence', float(cf_conf.mean())):.3f}."
        ),
        label="tab:t3_cf_indicators",
        column_spec="@{}Y Y S@{}",
        body=table_body,
        notes=[
            "Detection rates are percentages computed from the canonical Test 3 detailed results artifact.",
            "The last two rows are conditional rates over the computational-functionalist subset.",
        ],
    ) + "\n"

    out_path = OUT_CH4 / "t3_cf_indicators.tex"
    out_path.write_text(tex)
    print(f"  Written: {out_path}")


